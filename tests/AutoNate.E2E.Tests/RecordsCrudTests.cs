    [Fact]
    public async Task DeleteRecord_RemovesItFromTheList()
    {
        await using var session = await NewSignedInAsAdminAsync();
        var page = session.Page;
        var seeder = new ApiSeeder(page.APIRequest);

        var type = await seeder.CreateRecordTypeAsync(TestNames.ShortCode(), TestNames.Prefixed("del"));
        var record = await seeder.CreateRecordAsync(type.Id, TestNames.Prefixed("rec"));

        await page.GotoAsync($"/record/{record.Key}");

        await page.GetByRole(AriaRole.Button, new() { Name = "Delete" }).ClickAsync();

        // Confirm in the Mantine modal (title "Delete record"). The destructive
        // confirm button is the red "Delete" Button inside the dialog.
        var dialog = page.GetByRole(AriaRole.Dialog);
        await Assertions.Expect(dialog).ToBeVisibleAsync(new() { Timeout = 5_000 });
        await dialog.GetByRole(AriaRole.Button, new() { Name = "Delete" }).ClickAsync();

        // After confirm the SPA navigates back to /records/{code}.
        await page.WaitForURLAsync($"**/records/{type.ShortCode}",
            new() { Timeout = 10_000 });

        // And the deleted record's key shouldn't appear anywhere on the list.
        await Assertions.Expect(page.GetByText(record.Key)).Not.ToBeVisibleAsync();
    }

    [Fact]
    public async Task FiltersAndColumnsPopovers_OpenAndShowControls()
    {
        await using var session = await NewSignedInAsAdminAsync();
        var page = session.Page;
        var seeder = new ApiSeeder(page.APIRequest);

        var type = await seeder.CreateRecordTypeAsync(TestNames.ShortCode(), TestNames.Prefixed("filtcol"));
        await page.GotoAsync($"/records/{type.ShortCode}");

        // Wait for the search input to confirm the toolbar mounted before
        // poking the popover triggers.
        await Assertions.Expect(page.GetByPlaceholder("Search records…"))
            .ToBeVisibleAsync(new() { Timeout = 10_000 });

        await page.GetByRole(AriaRole.Button, new() { Name = "Columns" }).ClickAsync();
        // The Columns popover lists every column with a drag handle aria-label.
        await Assertions.Expect(page.GetByLabel("Drag to reorder").First)
            .ToBeVisibleAsync(new() { Timeout = 5_000 });

        // Re-click Columns to close it before opening Filters so the popovers
        // don't fight for focus.
        await page.GetByRole(AriaRole.Button, new() { Name = "Columns" }).ClickAsync();

        await page.GetByRole(AriaRole.Button, new() { Name = "Filters" }).ClickAsync();
        // The Filters popover renders an "Add filter" affordance; assert
        // *some* dialog/popover content rendered by checking the role=dialog.
        // Mantine Popovers in interactive mode use role="dialog".
        await Assertions.Expect(page.GetByRole(AriaRole.Dialog).First)
            .ToBeVisibleAsync(new() { Timeout = 5_000 });
    }
}
