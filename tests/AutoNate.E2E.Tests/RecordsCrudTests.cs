using AutoNate.E2E.Tests.Support;
using Microsoft.Playwright;
using Xunit;

namespace AutoNate.E2E.Tests;

/// <summary>
/// Phase 2 of the comprehensive E2E plan
/// (<c>docs/plans/2026-05-29-playwright-e2e-coverage.md</c>) — the
/// highest-value journey: a custom record type seeded via API, then full
/// list / create / edit / watch / comment / history / delete coverage driven
/// through the UI on top of it. Filters / Columns popovers are exercised
/// separately because they don't need a created record.
///
/// Each test mints its own record type + record so the suite stays order
/// independent against the shared ephemeral DB, and destructive flows (the
/// delete test) are safe now that the DB is isolated from the developer's
/// working <c>AutoNate</c>.
/// </summary>
public sealed class RecordsCrudTests : E2ETestBase
{
    public RecordsCrudTests(AutoNateE2EFixture fixture) : base(fixture) { }

    [Fact]
    public async Task RecordList_RendersHeadingAndNewButton()
    {
        await using var session = await NewSignedInAsAdminAsync();
        var page = session.Page;
        var seeder = new ApiSeeder(page.APIRequest);

        var typeName = TestNames.Prefixed("asset");
        var type = await seeder.CreateRecordTypeAsync(TestNames.ShortCode(), typeName);

        await page.GotoAsync($"/records/{type.ShortCode}");

        // The PageHeader title renders `<code>{code}</code>{name}` adjacent
        // with no whitespace, so the accessible name has no space between
        // them ("E71898e2e-asset-…"). Just assert the h1 mounted and let the
        // New-button check below — whose aria-label encodes the type name —
        // prove the right record type was loaded.
        await Assertions.Expect(page.Locator("h1").First)
            .ToBeVisibleAsync(new() { Timeout = 10_000 });

        await Assertions.Expect(
            page.GetByRole(AriaRole.Button, new() { Name = $"New {type.Name}" }))
            .ToBeVisibleAsync();
    }

    [Fact]
    public async Task CreateRecord_ViaUi_LandsOnDetailPageWithProvidedName()
    {
        await using var session = await NewSignedInAsAdminAsync();
        var page = session.Page;
        var seeder = new ApiSeeder(page.APIRequest);

        var typeName = TestNames.Prefixed("widget");
        var type = await seeder.CreateRecordTypeAsync(TestNames.ShortCode(), typeName);

        await page.GotoAsync($"/records/{type.ShortCode}");
        await page.GetByRole(AriaRole.Button, new() { Name = $"New {type.Name}" }).ClickAsync();

        // RecordCreate's PageHeader title: "New {name} {code}".
        await Assertions.Expect(
            page.GetByRole(AriaRole.Heading,
                new() { Name = $"New {type.Name} {type.ShortCode}" }))
            .ToBeVisibleAsync(new() { Timeout = 10_000 });

        var recordName = TestNames.Prefixed("rec");
        await page.GetByLabel("Name").FillAsync(recordName);
        await page.GetByRole(AriaRole.Button, new() { Name = "Create" }).ClickAsync();

        // Landed on /record/{key} (key is autogenerated, e.g. "E3F8C1-1").
        await page.WaitForURLAsync(new System.Text.RegularExpressions.Regex(@"/record/[A-Z0-9]+-\d+"),
            new() { Timeout = 10_000 });

        await Assertions.Expect(page.GetByText(recordName).First)
            .ToBeVisibleAsync(new() { Timeout = 5_000 });
    }

    [Fact]
    public async Task EditRecordName_PersistsAcrossReload()
    {
        await using var session = await NewSignedInAsAdminAsync();
        var page = session.Page;
        var seeder = new ApiSeeder(page.APIRequest);

        var type = await seeder.CreateRecordTypeAsync(TestNames.ShortCode(), TestNames.Prefixed("item"));
        var record = await seeder.CreateRecordAsync(type.Id, TestNames.Prefixed("rec"));

        await page.GotoAsync($"/record/{record.Key}");

        var updatedName = TestNames.Prefixed("renamed");
        var nameField = page.GetByLabel("Name");
        await nameField.WaitForAsync(new() { Timeout = 10_000 });
        await nameField.FillAsync(updatedName);
        await page.GetByRole(AriaRole.Button, new() { Name = "Save" }).ClickAsync();

        // RecordDetail flashes a Mantine Alert with role=alert and text "Saved." on
        // successful PATCH.
        await Assertions.Expect(page.GetByText("Saved."))
            .ToBeVisibleAsync(new() { Timeout = 10_000 });

        await page.ReloadAsync();
        await Assertions.Expect(page.GetByLabel("Name"))
            .ToHaveValueAsync(updatedName, new() { Timeout = 10_000 });
    }

    [Fact]
    public async Task WatchToggle_FlipsLabelOnClick()
    {
        await using var session = await NewSignedInAsAdminAsync();
        var page = session.Page;
        var seeder = new ApiSeeder(page.APIRequest);

        var type = await seeder.CreateRecordTypeAsync(TestNames.ShortCode(), TestNames.Prefixed("doc"));
        var record = await seeder.CreateRecordAsync(type.Id, TestNames.Prefixed("rec"));

        await page.GotoAsync($"/record/{record.Key}");

