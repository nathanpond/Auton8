        await watch.ClickAsync();

        // Hitting POST /api/records/{id}/watchers flips the local watch state
        // and re-renders the ActionIcon with aria-label="Unwatch".
        await Assertions.Expect(
            page.GetByRole(AriaRole.Button, new() { Name = "Unwatch" }))
            .ToBeVisibleAsync(new() { Timeout = 5_000 });
    }

